def auto_zh(tag: str) -> str | None:
    if tag in ZH:
        return ZH[tag]
    for color, czh in COLORS.items():
        prefix = color + " "
        if tag.startswith(prefix):
            rest = tag[len(prefix) :]
            if rest in ZH:
                return czh + ZH[rest]
            if rest in ITEMS:
                return czh + ITEMS[rest]
    return None


def check_tables() -> None:
    """ZH 與 ITEMS 對同一個字不能給不同的中文。

    ITEMS 只在顏色前綴那條路上用（blue coat -> 藍 + ITEMS["coat"]），ZH 是正表。
    兩張表講不一樣的話，面板上會並排出現「外套」和「棕大衣」—— 2026-09-18 實際
    就是這樣：coat 在 ZH 是外套、在 ITEMS 是大衣，kimono 是着物 vs 和服，
    pants 是長褲 vs 褲子。兩張表分開維護，不對照就永遠不會有人發現。
    """
    bad = [(k, ZH[k], ITEMS[k]) for k in ITEMS if k in ZH and ZH[k] != ITEMS[k]]
    if bad:
        for k, a, b in bad:
            print(f" 兩張表不一致 {k}: ZH={a} ITEMS={b}")
        raise SystemExit("add_zh.py 的 ZH 與 ITEMS 對同一個字給了不同的中文")


